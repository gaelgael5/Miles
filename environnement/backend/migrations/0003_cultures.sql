-- Référentiel des cultures : la liste est DONNÉE, pas saisie. L'utilisateur ACTIVE celles
-- dont l'installation se sert ; en-US est toujours active et sert de repli.
--
-- Données CLDR de Babel 2.17.0 — code BCP 47, libellé anglais, libellé dans la culture
-- elle-même — produites par portail/backend/scripts/generate_cultures_migration.py. Ce
-- fichier est le même artefact que la migration 0005 du portail et que la 0003 du module
-- d'enrôlement : le socle ne porte aucun SQL (décision du 27/10/2026), chaque produit
-- fournit donc les tables qu'il attend. La conséquence est assumée : l'écart entre les
-- TROIS schémas est tenu par la revue humaine, pas par un test — et c'est ici qu'il faut
-- regarder, les trois fichiers devant rester identiques au caractère près.
--
-- Ne pas éditer à la main ni régénérer une fois jouée : une nouvelle liste passe par une
-- nouvelle migration, qui ne touche pas à l'état actif des cultures existantes.
CREATE TABLE cultures (
    code text PRIMARY KEY CHECK (code ~ '^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$'),
    label_en text NOT NULL CHECK (char_length(label_en) BETWEEN 1 AND 200),
    label_native text NOT NULL CHECK (char_length(label_native) BETWEEN 1 AND 200),
    active boolean NOT NULL DEFAULT false,
    -- en-US est le repli garanti de tout libellé déclinable : la base elle-même
    -- refuse de la désactiver, quoi que fasse le code.
    CONSTRAINT cultures_fallback_always_active CHECK (code <> 'en-US' OR active)
);

